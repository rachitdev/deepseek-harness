#!/usr/bin/env node
// Writes src/gui/zone_aliases.rs: every IANA zone name the bundled tz database
// knows whose canonical spelling under Node's ICU differs from its own.
//
// TypeScript stores `new Intl.DateTimeFormat('en-US', { timeZone }).resolvedOptions().timeZone`
// (so `Asia/Kolkata` is stored as `Asia/Calcutta`). A stored record must carry the
// same text in both hosts, so this table reproduces ICU's choice.
//
//   node tools/gen-zone-aliases.mjs <names.json> > src/gui/zone_aliases.rs
//
// <names.json> is the JSON array of names from jiff's bundled database; produce it with
// the `jiff::tz::db().available()` iterator.
import { readFileSync } from 'node:fs'

const names = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const shape = /^[A-Za-z][A-Za-z0-9_+.-]*(?:\/[A-Za-z0-9_+.-]+)+$/
const rows = []
for (const name of names.filter(n => shape.test(n)).sort()) {
  let canonical
  try { canonical = new Intl.DateTimeFormat('en-US', { timeZone: name }).resolvedOptions().timeZone } catch { continue }
  if (canonical !== name) rows.push([name, canonical])
}
console.log(`//! Generated by tools/gen-zone-aliases.mjs with Node ${process.version} (ICU ${process.versions.icu}, tz ${process.versions.tz}). Do not edit.
//!
//! Zone names whose canonical spelling under ICU differs from the tz database's own.

/// \`(database name, ICU canonical name)\`, sorted by database name.
pub const ALIASES: &[(&str, &str)] = &[`)
for (const [name, canonical] of rows) console.log(`    (${JSON.stringify(name)}, ${JSON.stringify(canonical)}),`)
console.log('];')
